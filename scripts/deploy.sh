#!/usr/bin/env bash
# Build / validate the Hermes-Agent_course site.
# - validates every .html file (well-formedness + basic checks)
# - writes a version manifest used to prove a deploy actually landed
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

echo "==> Validating HTML files"
shopt -s nullglob
files=( *.html )
if [ ${#files[@]} -eq 0 ]; then
  echo "ERROR: no HTML files found in $ROOT" >&2
  exit 1
fi

for f in "${files[@]}"; do
  # 1. must be a non-empty regular file
  if [ ! -s "$f" ]; then
    echo "ERROR: $f is empty" >&2; exit 1
  fi
  # 2. must start with a doctype and close its html tag
  head -c 4 "$f" | tr '[:upper:]' '[:lower:]' | grep -q '^<!do' || { echo "ERROR: $f missing <!DOCTYPE" >&2; exit 1; }
  grep -qi '</html>' "$f" || { echo "ERROR: $f missing </html>" >&2; exit 1; }
  # 3. balanced-ish check: every <html has a matching </html>
  open=$(grep -o '<html' "$f" | wc -l); close=$(grep -o '</html>' "$f" | wc -l)
  [ "$open" = "1" ] && [ "$close" = "1" ] || { echo "ERROR: $f unbalanced <html> (open=$open close=$close)" >&2; exit 1; }
  echo "    ok: $f"
done

echo "==> Writing version manifest"
SHA="$(git rev-parse --short HEAD 2>/dev/null || echo no-git)"
BUILD="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
{
  echo "<!-- Generated by deploy.sh — do not edit by hand -->"
  echo "<p>build: ${SHA} · ${BUILD} · ${#files[@]} pages</p>"
} > "$ROOT/.build-info.txt"
echo "    wrote .build-info.txt (build ${SHA})"

echo "==> Build OK: ${#files[@]} HTML pages validated"
